package dicom

import (
	"fmt"

	"go.uber.org/zap"
	"screening-gateway/internal/storage"
)

// WorklistHandler handles DICOM Modality Worklist (MWL) C-FIND queries
type WorklistHandler struct {
	storage *storage.WorklistStorage
	logger  *zap.Logger
}

// NewWorklistHandler creates a new worklist query handler
func NewWorklistHandler(worklistStorage *storage.WorklistStorage, logger *zap.Logger) *WorklistHandler {
	return &WorklistHandler{
		storage: worklistStorage,
		logger:  logger,
	}
}

// WorklistQuery represents a DICOM worklist C-FIND query
type WorklistQuery struct {
	Modality      *string // Scheduled modality (e.g., "MG")
	ScheduledDate *string // Scheduled date in YYYYMMDD format
	PatientID     *string // Patient identifier
}

// WorklistResponse represents a DICOM worklist item to be returned
// This struct will be converted to a DICOM dataset by the networking layer
type WorklistResponse struct {
	// Patient Identification Module
	PatientName      string
	PatientID        string
	PatientBirthDate string
	PatientSex       string

	// Scheduled Procedure Step
	Modality                              string
	ScheduledStationAETitle               string
	ScheduledProcedureStepStartDate       string
	ScheduledProcedureStepStartTime       string
	ScheduledPerformingPhysicianName      string
	ScheduledProcedureStepDescription     string
	ScheduledProcedureStepID              string

	// Study Module
	AccessionNumber              string
	StudyInstanceUID             string
	StudyID                      string
	RequestedProcedureDescription string
	RequestedProcedureID         string
}

// FindWorklist queries the worklist database and returns matching items
// Matches Python find_worklist() behavior
func (h *WorklistHandler) FindWorklist(query *WorklistQuery) ([]*WorklistResponse, error) {
	h.logger.Info("Received worklist query",
		zap.Stringp("modality", query.Modality),
		zap.Stringp("scheduled_date", query.ScheduledDate),
		zap.Stringp("patient_id", query.PatientID),
	)

	// Query database with status filter (only return SCHEDULED items)
	// Note: Python implementation only returns SCHEDULED status
	items, err := h.storage.FindWorklistItems(
		query.Modality,
		query.ScheduledDate,
		query.PatientID,
		storage.WorklistStatusScheduled,
	)

	if err != nil {
		h.logger.Error("Failed to query worklist database", zap.Error(err))
		return nil, fmt.Errorf("failed to query worklist: %w", err)
	}

	h.logger.Info("Database query returned items", zap.Int("count", len(items)))

	// Convert database items to DICOM worklist responses
	responses := make([]*WorklistResponse, 0, len(items))
	for _, item := range items {
		response := h.convertToWorklistResponse(item)
		responses = append(responses, response)
	}

	h.logger.Info("Returning worklist items", zap.Int("count", len(responses)))

	return responses, nil
}

// convertToWorklistResponse converts a database worklist item to a DICOM response
// Matches Python implementation exactly
func (h *WorklistHandler) convertToWorklistResponse(item *storage.WorklistItem) *WorklistResponse {
	// Get study instance UID (use existing or will need to be generated by caller)
	studyInstanceUID := ""
	if item.StudyInstanceUID.Valid {
		studyInstanceUID = item.StudyInstanceUID.String
	}

	// Get study description
	studyDescription := ""
	if item.StudyDescription.Valid {
		studyDescription = item.StudyDescription.String
	}

	return &WorklistResponse{
		// Patient Identification Module
		PatientName:      item.PatientName,
		PatientID:        item.PatientID,
		PatientBirthDate: item.PatientBirthDate,
		PatientSex:       item.PatientSex,

		// Scheduled Procedure Step
		Modality:                              item.Modality,
		ScheduledStationAETitle:               "", // Empty in Python implementation
		ScheduledProcedureStepStartDate:       item.ScheduledDate,
		ScheduledProcedureStepStartTime:       item.ScheduledTime,
		ScheduledPerformingPhysicianName:      "", // Empty in Python implementation
		ScheduledProcedureStepDescription:     studyDescription,
		ScheduledProcedureStepID:              item.AccessionNumber,

		// Study Module
		AccessionNumber:              item.AccessionNumber,
		StudyInstanceUID:             studyInstanceUID,
		StudyID:                      item.AccessionNumber, // Use accession as study ID
		RequestedProcedureDescription: studyDescription,
		RequestedProcedureID:         item.AccessionNumber,
	}
}

